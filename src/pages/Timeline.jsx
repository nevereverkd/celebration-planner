/**
 * Timeline.jsx
 * Event milestone timeline with AI generation and progress tracking.
 */

import React, { useState } from 'react'
import { Plus, Check, Trash2, Sparkles, Calendar } from 'lucide-react'
import { useApp, ActionTypes } from '../context/AppContext'
import { useToast } from '../hooks/useToast'
import { calcMilestoneProgress, PRIORITY_CONFIG, formatDate } from '../utils/helpers'
import { generateTimeline } from '../utils/gemini'
import Modal from '../components/Modal'
import EmptyState from '../components/EmptyState'
import ProgressRing from '../components/ProgressRing'
import styles from './Timeline.module.css'

const CATEGORIES = ['booking', 'design', 'logistics', 'communication', 'final']
const CATEGORY_CONFIG = {
  booking:       { emoji: '📋', color: '#8b5cf6', label: 'Booking' },
  design:        { emoji: '🎨', color: '#ec4899', label: 'Design' },
  logistics:     { emoji: '🚚', color: '#f59e0b', label: 'Logistics' },
  communication: { emoji: '📣', color: '#3b82f6', label: 'Communication' },
  final:         { emoji: '✅', color: '#10b981', label: 'Final Prep' },
}

export default function Timeline() {
  const { state, dispatch }      = useApp()
  const { toast }                = useToast()
  const event                    = state.events.find(e => e.id === state.activeEventId)
  const [showModal, setShowModal] = useState(false)
  const [aiLoading, setAiLoading] = useState(false)
  const [form, setForm]          = useState({ title: '', description: '', daysBeforeEvent: 30, category: 'booking', priority: 'medium' })

  if (!event) return <EmptyState emoji="📅" title="No event selected" description="Create or select an event first." />

  const progress = calcMilestoneProgress(event.milestones)
  const milestones = [...(event.milestones || [])].sort((a, b) => (b.daysBeforeEvent || 0) - (a.daysBeforeEvent || 0))

  function handleAdd() {
    if (!form.title.trim()) { toast('Please enter a milestone title.', 'error'); return }
    dispatch({
      type: ActionTypes.ADD_MILESTONE,
      payload: { ...form, daysBeforeEvent: Number(form.daysBeforeEvent), eventId: event.id },
    })
    toast('Milestone added! 📅', 'success')
    setShowModal(false)
  }

  function handleToggle(id) {
    dispatch({ type: ActionTypes.TOGGLE_MILESTONE, payload: { eventId: event.id, id } })
  }

  function handleDelete(id) {
    if (!confirm('Delete this milestone?')) return
    dispatch({ type: ActionTypes.DELETE_MILESTONE, payload: { id, eventId: event.id } })
    toast('Milestone removed.', 'info')
  }

  async function handleAiGenerate() {
    setAiLoading(true)
    try {
      const items = await generateTimeline(state.apiKey, event)
      items.forEach(item => {
        dispatch({ type: ActionTypes.ADD_MILESTONE, payload: { ...item, eventId: event.id } })
      })
      toast(`✨ ${items.length} milestones generated by AI!`, 'success')
    } catch (err) {
      toast(err.message || 'AI generation failed.', 'error')
    } finally {
      setAiLoading(false)
    }
  }

  return (
    <div className={styles.page}>
      {/* Header */}
      <div className="section-header" style={{ marginBottom: '1.75rem' }}>
        <div>
          <h1 className="section-title" style={{ fontSize: '1.75rem' }}>📅 Planning Timeline</h1>
          <p className="section-subtitle">Track milestones for <strong>{event.name}</strong></p>
        </div>
        <div style={{ display: 'flex', gap: '0.75rem', flexWrap: 'wrap' }}>
          <button className="btn btn-secondary" onClick={handleAiGenerate} disabled={aiLoading}>
            <Sparkles size={16} /> {aiLoading ? 'Generating…' : 'AI Generate Timeline'}
          </button>
          <button className="btn btn-primary" onClick={() => setShowModal(true)}>
            <Plus size={16} /> Add Milestone
          </button>
        </div>
      </div>

      {/* Progress Summary */}
      <div className={styles.progressRow}>
        <ProgressRing pct={progress.pct} size={72} stroke={7} color="#8b5cf6" label={`${progress.pct}%`} />
        <div>
          <div style={{ fontWeight: 800, fontSize: '1.25rem', color: '#1e293b' }}>
            {progress.completed} of {progress.total} milestones completed
          </div>
          <div style={{ color: '#64748b', fontSize: '0.9rem', marginTop: '0.25rem' }}>
            {progress.total - progress.completed} remaining · Keep going! 🚀
          </div>
          <div className="progress" style={{ marginTop: '0.75rem', maxWidth: '320px' }}>
            <div className="progress-bar" style={{ width: `${progress.pct}%` }} />
          </div>
        </div>
      </div>

      {/* Timeline */}
      {milestones.length === 0 ? (
        <EmptyState
          emoji="🗓️"
          title="No milestones yet!"
          description="Add milestones manually or let AI generate a full timeline for your event."
          action={
            <button className="btn btn-primary" onClick={handleAiGenerate} disabled={aiLoading}>
              <Sparkles size={16} /> Generate with AI
            </button>
          }
        />
      ) : (
        <div className={styles.timeline}>
          {milestones.map((m, i) => {
            const cat = CATEGORY_CONFIG[m.category] || CATEGORY_CONFIG.booking
            const pri = PRIORITY_CONFIG[m.priority] || PRIORITY_CONFIG.medium
            return (
              <div key={m.id} className={`${styles.item} ${m.completed ? styles.itemDone : ''}`}>
                {/* Line */}
                <div className={styles.lineWrap}>
                  <div className={styles.line} style={{ background: m.completed ? '#10b981' : '#e2e8f0' }} />
                  <button
                    className={styles.dot}
                    style={{
                      background: m.completed ? 'linear-gradient(135deg, #10b981, #059669)' : `linear-gradient(135deg, ${cat.color}, ${cat.color}bb)`,
                      boxShadow: m.completed ? '0 0 0 4px rgba(16,185,129,0.2)' : `0 0 0 4px ${cat.color}25`,
                    }}
                    onClick={() => handleToggle(m.id)}
                    aria-label={m.completed ? 'Mark incomplete' : 'Mark complete'}
                    title={m.completed ? 'Click to undo' : 'Click to complete'}
                  >
                    {m.completed && <Check size={14} color="white" />}
                  </button>
                </div>

                {/* Content */}
                <div className={styles.itemContent}>
                  <div className={styles.itemHeader}>
                    <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem', flexWrap: 'wrap' }}>
                      <span className={styles.catEmoji}>{cat.emoji}</span>
                      <span className={`${styles.itemTitle} ${m.completed ? styles.titleDone : ''}`}>{m.title}</span>
                      <span className={`badge ${pri.badge}`}>{pri.label}</span>
                    </div>
                    <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
                      {m.daysBeforeEvent > 0 && (
                        <span className="badge badge-blue">{m.daysBeforeEvent}d before</span>
                      )}
                      <button className="btn btn-ghost btn-sm" onClick={() => handleDelete(m.id)} style={{ color: '#ef4444' }} aria-label="Delete">
                        <Trash2 size={13} />
                      </button>
                    </div>
                  </div>
                  {m.description && (
                    <div className={styles.itemDesc}>{m.description}</div>
                  )}
                </div>
              </div>
            )
          })}
        </div>
      )}

      {/* Add Milestone Modal */}
      <Modal isOpen={showModal} onClose={() => setShowModal(false)} title="📅 Add Milestone">
        <div style={{ display: 'flex', flexDirection: 'column', gap: '1.125rem' }}>
          <div className="input-group">
            <label className="label">Title *</label>
            <input className="input" value={form.title} onChange={e => setForm(f => ({ ...f, title: e.target.value }))} placeholder="e.g., Book the venue" maxLength={100} autoFocus />
          </div>
          <div className="input-group">
            <label className="label">Description</label>
            <textarea className="input" value={form.description} onChange={e => setForm(f => ({ ...f, description: e.target.value }))} placeholder="Details about this milestone..." rows={2} maxLength={300} />
          </div>
          <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr 1fr', gap: '1rem' }}>
            <div className="input-group">
              <label className="label">Days Before Event</label>
              <input className="input" type="number" value={form.daysBeforeEvent} onChange={e => setForm(f => ({ ...f, daysBeforeEvent: e.target.value }))} min={0} max={730} />
            </div>
            <div className="input-group">
              <label className="label">Category</label>
              <select className="input" value={form.category} onChange={e => setForm(f => ({ ...f, category: e.target.value }))}>
                {CATEGORIES.map(c => <option key={c} value={c}>{CATEGORY_CONFIG[c].label}</option>)}
              </select>
            </div>
            <div className="input-group">
              <label className="label">Priority</label>
              <select className="input" value={form.priority} onChange={e => setForm(f => ({ ...f, priority: e.target.value }))}>
                <option value="high">High 🔴</option>
                <option value="medium">Medium 🟡</option>
                <option value="low">Low 🟢</option>
              </select>
            </div>
          </div>
          <button className="btn btn-primary" onClick={handleAdd} style={{ width: '100%' }}>Add Milestone</button>
        </div>
      </Modal>
    </div>
  )
}

